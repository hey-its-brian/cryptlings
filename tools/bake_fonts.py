#!/usr/bin/env python3
"""Bake TTF fonts into 4bpp anti-aliased bitmap fonts for the device.

Output: src/assets/fonts.h (one const struct per font, stored in flash).
Glyphs cover printable ASCII (0x20..0x7E). Each glyph is a tight 4bpp alpha
box (two pixels per byte, high nibble first) plus its offset from the pen
position on the baseline and its advance width.

Fonts are SIL Open Font License (Courier Prime, Grenze, Grenze Gotisch,
Patrick Hand); the TTFs live in tools/fonts/.

Usage: python3 tools/bake_fonts.py   (from the repo root)
"""
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, "tools", "fonts")
OUT = os.path.join(ROOT, "src", "assets", "fonts.h")

# name, ttf, pixel size  (sizes follow Brief A3, 12px floor)
SPECS = [
    ("font_body12b", "CourierPrime-Bold.ttf", 12),     # status strip, small labels, stamps
    ("font_body14",  "CourierPrime-Regular.ttf", 14),  # body copy
    ("font_body14b", "CourierPrime-Bold.ttf", 14),     # buttons
    ("font_head16",  "Grenze-SemiBold.ttf", 16),       # headers, tabs, species names
    ("font_hand16",  "PatrickHand-Regular.ttf", 16),   # polaroid captions, notes
    ("font_title24", "GrenzeGotisch-Bold.ttf", 24),    # screen titles, stage stamp
    ("font_title32", "GrenzeGotisch-Bold.ttf", 32),    # splash
]
FIRST, LAST = 0x20, 0x7E


def bake(name, ttf, size):
    font = ImageFont.truetype(os.path.join(FONTS, ttf), size)
    ascent, descent = font.getmetrics()
    glyphs, data = [], bytearray()
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        adv = int(round(font.getlength(ch)))
        # Render on a generous canvas with the baseline at y = ascent + pad.
        pad = 8
        W, H = size * 3 + pad * 2, ascent + descent + pad * 2
        img = Image.new("L", (W, H), 0)
        ImageDraw.Draw(img).text((pad, pad), ch, font=font, fill=255)
        bbox = img.getbbox()
        if bbox is None:
            glyphs.append((len(data), 0, 0, 0, 0, adv))
            continue
        x0, y0, x1, y1 = bbox
        w, h = x1 - x0, y1 - y0
        crop = img.crop(bbox)
        px = list(crop.tobytes())
        off = len(data)
        row_bytes = (w + 1) // 2
        for y in range(h):
            for xb in range(row_bytes):
                a = px[y * w + xb * 2] >> 4
                b = (px[y * w + xb * 2 + 1] >> 4) if xb * 2 + 1 < w else 0
                data.append((a << 4) | b)
        xoff = x0 - pad
        yoff = y0 - pad - ascent          # relative to baseline (negative = above)
        glyphs.append((off, w, h, xoff, yoff, adv))
    return {"name": name, "ascent": ascent, "descent": descent, "line": ascent + descent,
            "glyphs": glyphs, "data": data, "size": size}


def emit(fonts):
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    L = ["// Generated by tools/bake_fonts.py. Do not edit.",
         "#pragma once", "#include \"../app/gfx.h\"", ""]
    total = 0
    for f in fonts:
        n = f["name"]
        L.append(f"static const uint8_t {n}_bits[] = {{")
        d = f["data"]
        for i in range(0, len(d), 24):
            L.append("  " + ",".join(str(b) for b in d[i:i + 24]) + ",")
        L.append("};")
        L.append(f"static const Glyph {n}_glyphs[] = {{")
        for g in f["glyphs"]:
            L.append("  {%d,%d,%d,%d,%d,%d}," % g)
        L.append("};")
        L.append(f"static const Font {n} = {{ {n}_bits, {n}_glyphs, {FIRST}, {LAST}, "
                 f"{f['ascent']}, {f['line']} }};")
        L.append("")
        total += len(d) + len(f["glyphs"]) * 8
    with open(OUT, "w") as fh:
        fh.write("\n".join(L))
    print(f"wrote {OUT}: {len(fonts)} fonts, about {total // 1024} KB")


if __name__ == "__main__":
    emit([bake(*s) for s in SPECS])
