#!/usr/bin/env python3
"""Quantize the rendered art (tools/art/out/*.png, from tools/art/render.js)
into 4bpp indexed sprites with a 16-entry RGBA palette each, and emit
src/assets/art.h.

Each creature frame is cropped to its visible box (offset kept in the
sprite) so the flash cost is roughly half of the full 100 x 100 box.
Semi-transparent edges (anti-aliasing, soft shadows, the blurry form) keep
their alpha through the palette, so they blend on the device.

Usage: node tools/art/render.js && python3 tools/bake_sprites.py
"""
import os
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "tools", "art", "out")
OUT = os.path.join(ROOT, "src", "assets", "art.h")
SHEET = os.path.join(ROOT, "tools", "art", "contact_sheet.png")

SPECIES = ["mothman", "bigfoot", "nessie", "nightcrawler"]
FORMS = ["egg", "whisper", "rumor", "sighting", "legend", "blurry", "hoax"]
REAL_FORMS = FORMS[:6]   # HOAX reuses LEGEND art with a gag overlay in code
MOODS = ["happy", "neutral", "sad", "sleep", "blink"]
TODS = ["dusk", "night", "dawn", "day"]
ICONS = ["belly", "cheer", "rest", "myst", "tidy", "play", "lights", "case", "loch", "walk",
         "pants", "lamp", "forage", "treat"]


def quantize(img, crop=True):
    img = img.convert("RGBA")
    px = img.load()
    w, h = img.size
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            if a < 24:
                px[x, y] = (0, 0, 0, 0)
            elif a > 232:
                px[x, y] = (r, g, b, 255)
    ox = oy = 0
    if crop:
        bbox = img.getbbox()
        if bbox:
            ox, oy = bbox[0], bbox[1]
            img = img.crop(bbox)
    w, h = img.size
    has_transparent = any(p[3] == 0 for p in img.getdata())
    q = img.quantize(colors=16, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.NONE)
    pal = q.getpalette(rawmode="RGBA")[: 16 * 4]
    pal += [0] * (64 - len(pal))
    entries = [tuple(pal[i * 4:i * 4 + 4]) for i in range(16)]
    idx = list(q.tobytes())
    # Put a fully transparent entry at index 0.
    t = next((i for i, e in enumerate(entries) if e[3] == 0), None)
    if t is None:
        t = 15 if has_transparent else None
        if t is not None:
            entries[t] = (0, 0, 0, 0)
    if t is not None and t != 0:
        entries[0], entries[t] = entries[t], entries[0]
        idx = [t if v == 0 else 0 if v == t else v for v in idx]
    # Any source pixel that was fully transparent must map to index 0.
    src = list(img.getdata())
    if t is not None:
        idx = [0 if src[i][3] == 0 else (v if v != 0 else _nearest(entries, src[i])) for i, v in enumerate(idx)]
    pal32 = [(a << 24) | (r << 16) | (g << 8) | b for (r, g, b, a) in entries]
    rb = (w + 1) // 2
    data = bytearray()
    for y in range(h):
        for xb in range(rb):
            a = idx[y * w + xb * 2]
            b = idx[y * w + xb * 2 + 1] if xb * 2 + 1 < w else 0
            data.append((a << 4) | b)
    return {"w": w, "h": h, "ox": ox, "oy": oy, "pal": pal32, "data": data, "idx": idx, "entries": entries}


def _nearest(entries, p):
    best, bi = 1e9, 1
    for i, e in enumerate(entries[1:], 1):
        d = sum((a - b) ** 2 for a, b in zip(e, p))
        if d < best:
            best, bi = d, i
    return bi


def preview(s):
    img = Image.new("RGBA", (s["w"], s["h"]))
    img.putdata([s["entries"][i] for i in s["idx"]])
    return img


def emit_sprite(L, name, s):
    L.append(f"static const uint32_t {name}_pal[16] = {{" + ",".join(f"0x{v:08X}" for v in s["pal"]) + "};")
    L.append(f"static const uint8_t {name}_idx[] = {{")
    d = s["data"]
    for i in range(0, len(d), 32):
        L.append("  " + ",".join(str(b) for b in d[i:i + 32]) + ",")
    L.append("};")
    L.append(f"static const Sprite {name} = {{ {s['w']}, {s['h']}, {s['ox']}, {s['oy']}, {name}_pal, {name}_idx }};")
    return len(d) + 64


def main():
    L = ["// Generated by tools/bake_sprites.py from tools/art. Do not edit.", "#pragma once",
         "#include \"../app/gfx.h\"", ""]
    total = 0
    # creatures
    for si, sp in enumerate(SPECIES):
        for fi, form in enumerate(REAL_FORMS):
            for mi, mood in enumerate(MOODS):
                s = quantize(Image.open(os.path.join(SRC, f"spr_{sp}_{form}_{mood}.png")))
                total += emit_sprite(L, f"spr_{sp}_{form}_{mood}", s)
    L.append("")
    L.append("// [species][form][mood]  forms: egg whisper rumor sighting legend blurry; moods: happy neutral sad sleep blink")
    L.append("static const Sprite* const CREATURE[4][6][5] = {")
    for sp in SPECIES:
        L.append("  {")
        for form in REAL_FORMS:
            L.append("    {" + ",".join(f"&spr_{sp}_{form}_{m}" for m in MOODS) + "},")
        L.append("  },")
    L.append("};")
    L.append("")
    # scenes
    for sp in SPECIES:
        for tod in TODS:
            s = quantize(Image.open(os.path.join(SRC, f"scene_{sp}_{tod}.png")), crop=False)
            total += emit_sprite(L, f"scene_{sp}_{tod}", s)
    L.append("// [species][tod] tod: dusk night dawn day")
    L.append("static const Sprite* const SCENE[4][4] = {")
    for sp in SPECIES:
        L.append("  {" + ",".join(f"&scene_{sp}_{t}" for t in TODS) + "},")
    L.append("};")
    L.append("")
    # icons (keep the 16 x 16 box: crop=False so they align)
    for ic in ICONS:
        s = quantize(Image.open(os.path.join(SRC, f"icon_{ic}.png")), crop=False)
        total += emit_sprite(L, f"icon_{ic}", s)
    L.append("")
    with open(OUT, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print(f"wrote {OUT}: about {total // 1024} KB of art")
    # A quick look at night/neutral and sleep for review.
    prev = Image.new("RGBA", (6 * 2 * 104, 4 * 104), (11, 13, 18, 255))
    for si, sp in enumerate(SPECIES):
        for fi, form in enumerate(REAL_FORMS):
            for k, mood in enumerate(["neutral", "sleep"]):
                s = quantize(Image.open(os.path.join(SRC, f"spr_{sp}_{form}_{mood}.png")))
                prev.alpha_composite(preview(s), ((fi * 2 + k) * 104 + s["ox"], si * 104 + s["oy"]))
    prev.save(SHEET)
    print(f"contact sheet: {SHEET}")


if __name__ == "__main__":
    main()
